#!/usr/bin/env bash
# Creates backend/.env with fresh service credentials. Never prints secret values.
#   WEB_ENV       where to copy DATABASE_URL, BETTER_AUTH_SECRET, Google keys from (default ../web/.env)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/.env"
WEB_ENV="${WEB_ENV:-$ROOT/../web/.env}"

if [[ -f "$ENV_FILE" && "${1:-}" != "--force" ]]; then
  echo "backend/.env already exists; leaving it alone (pass --force to regenerate service credentials)."
  exit 0
fi

python3 -I - "$ENV_FILE" "$WEB_ENV" <<'PY'
import os, secrets, sys
out, web_env = sys.argv[1:3]

def read(path):
    values = {}
    if not os.path.exists(path):
        return values
    for line in open(path):
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key.strip()] = value
    return values

web = read(web_env)
token = lambda n=32: secrets.token_hex(n)
copied, missing = [], []

def take(source, key, target=None, default=""):
    value = source.get(key, "")
    (copied if value else missing).append(target or key)
    return value or default

env = {
    "NODE_ENV": "development",
    "LOG_LEVEL": "info",
    "PORT": "4000",
    "WORKER_METRICS_PORT": "4001",
    "PUBLIC_WEB_URL": "http://localhost:3000",
    "WEB_ORIGINS": "http://localhost:3000",
    "DATABASE_URL": take(web, "DATABASE_URL"),
    "BETTER_AUTH_SECRET": take(web, "BETTER_AUTH_SECRET") or token(32),
    "BETTER_AUTH_URL": "http://localhost:3000",
    "GOOGLE_CLIENT_ID": take(web, "GOOGLE_CLIENT_ID"),
    "GOOGLE_CLIENT_SECRET": take(web, "GOOGLE_CLIENT_SECRET"),
    "REDIS_HOST": "localhost",
    "REDIS_PORT": "6390",
    "REDIS_PASSWORD": token(24),
    "REDIS_DB": "0",
    "RABBITMQ_HOST": "localhost",
    "RABBITMQ_PORT": "5682",
    "RABBITMQ_USERNAME": "xray",
    "RABBITMQ_PASSWORD": token(24),
    "RABBITMQ_VHOST": "xray",
    "METRICS_TOKEN": token(24),
    "OPS_TOKEN": token(24),
    "GRAFANA_ADMIN_PASSWORD": token(12),
    # Email stays on the log transport until you add this app's own SES credentials and sender.
    "EMAIL_PROVIDER": "log",
    "EMAIL_FROM": "Cultural X-Ray <no-reply@example.com>",
    "EMAIL_REPLY_TO": "",
    "AWS_REGION": "us-east-1",
    "AWS_ACCESS_KEY_ID": "",
    "AWS_SECRET_ACCESS_KEY": "",
}

with open(out, "w") as f:
    f.write("# Generated by scripts/init-env.sh. Keep out of git.\n")
    for key, value in env.items():
        f.write(f'{key}="{value}"\n')
os.chmod(out, 0o600)

print("backend/.env written (secrets not shown).")
print("  generated: REDIS_PASSWORD, RABBITMQ_PASSWORD, METRICS_TOKEN, OPS_TOKEN, GRAFANA_ADMIN_PASSWORD")
print("  copied:    " + ", ".join(copied))
if missing:
    print("  missing:   " + ", ".join(missing) + "  (fill these in by hand)")
print("  email:     EMAIL_PROVIDER=log. Add your SES keys, EMAIL_FROM and set EMAIL_PROVIDER=ses to send.")
PY

# Prometheus reads the metrics token from a file so it never lives in prometheus.yml.
grep -E '^METRICS_TOKEN=' "$ENV_FILE" | cut -d'"' -f2 | tr -d '\n' > "$ROOT/devops/prometheus/metrics_token"
chmod 644 "$ROOT/devops/prometheus/metrics_token"
echo "devops/prometheus/metrics_token written."
